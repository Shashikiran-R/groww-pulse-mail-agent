"""
Google Doc Formatter.

Converts raw Markdown pulse intelligence reports into beautifully structured,
cleanly styled text layouts optimized for Google Docs readability.
Replaces raw Markdown syntax (#, ##, **, >) with executive header dividers,
bulleted key metrics, and clean quotation blocks.
"""

from __future__ import annotations

import re


def format_for_google_doc(md_text: str) -> str:
    """
    Format raw Markdown pulse report into an executive Google Doc layout.

    Args:
        md_text: Raw Markdown text containing headings, lists, quotes.

    Returns:
        Professionally formatted plain text string with Unicode dividers and clean indentation.
    """
    if not md_text or not md_text.strip():
        return ""

    lines = md_text.splitlines()
    formatted: list[str] = []
    divider = "═" * 70
    sub_divider = "─" * 70

    for line in lines:
        stripped = line.strip()
        if not stripped:
            continue

        # Title: # Groww Weekly Pulse — 2026-W40
        if stripped.startswith("# "):
            title = stripped[2:].strip().replace("‑", "-")
            formatted.append(divider)
            formatted.append(f"📈 {title.upper()}")
            formatted.append("   Weekly Executive Review Pulse & Customer Intelligence")
            formatted.append(divider)
            formatted.append("")
            continue

        # Executive Summary: **Executive Summary:** ...
        if stripped.startswith("**Executive Summary:**") or stripped.startswith("Executive Summary:"):
            content = re.sub(r"^\*{0,2}Executive Summary:\*{0,2}\s*", "", stripped)
            formatted.append("📌 EXECUTIVE SUMMARY")
            formatted.append(f"   {content}")
            formatted.append("")
            continue

        # Top Themes Header: ## 📊 Top Themes
        if re.match(r"^##\s+.*Top Themes", stripped, re.IGNORECASE):
            formatted.append(sub_divider)
            formatted.append("📊 TOP CUSTOMER THEMES")
            formatted.append(sub_divider)
            formatted.append("")
            continue

        # Theme Subheading: ### 1. Theme Name (N reviews, P% negative) ↑
        theme_match = re.match(r"^###\s+(\d+)\.\s+([^(]+)\s*\(([^)]+)\)\s*([↑↓→]?)", stripped)
        if theme_match:
            idx, name, stats, trend = theme_match.groups()
            trend_str = f" [Trend: {trend}]" if trend else ""
            formatted.append(f"[{idx}] {name.strip().upper()}")
            formatted.append(f"    • Volume & Sentiment: {stats.strip()}{trend_str}")
            continue

        # User Quotes Header: ## 💬 User Quotes
        if re.match(r"^##\s+.*User Quotes", stripped, re.IGNORECASE):
            formatted.append(sub_divider)
            formatted.append("💬 VERBATIM CUSTOMER VOICES")
            formatted.append(sub_divider)
            formatted.append("")
            continue

        # Quote line: > ★☆☆☆☆ — "quote" — *Author, Date*
        if stripped.startswith(">"):
            raw_quote = stripped[1:].strip()
            raw_quote = re.sub(r"\*([^*]+)\*", r"\1", raw_quote)
            formatted.append(f"   {raw_quote}")
            formatted.append("")
            continue

        # Action Ideas Header: ## 💡 Action Ideas
        if re.match(r"^##\s+.*Action Ideas", stripped, re.IGNORECASE):
            formatted.append(sub_divider)
            formatted.append("💡 STRATEGIC ACTION RECOMMENDATIONS")
            formatted.append(sub_divider)
            formatted.append("")
            continue

        # Action item: 1. **[Theme]** Action...
        action_match = re.match(r"^(\d+)\.\s+\*{0,2}\[([^\]]+)\]\*{0,2}\s*(.*)", stripped)
        if action_match:
            num, theme, text = action_match.groups()
            formatted.append(f"   [{num}] {theme.strip()}:")
            formatted.append(f"       {text.strip()}")
            formatted.append("")
            continue

        # General markdown headings (## or ###) that didn't match specialized blocks
        if stripped.startswith("### "):
            heading = stripped[4:].strip()
            formatted.append(f"▶ {heading.upper()}")
            continue
        elif stripped.startswith("## "):
            heading = stripped[3:].strip()
            formatted.append(sub_divider)
            formatted.append(f"▶ {heading.upper()}")
            formatted.append(sub_divider)
            formatted.append("")
            continue

        # Details paragraphs
        clean_line = re.sub(r"\*\*([^*]+)\*\*", r"\1", stripped)
        clean_line = re.sub(r"\*([^*]+)\*", r"\1", clean_line)
        formatted.append(f"    • Analysis: {clean_line}")
        formatted.append("")

    formatted.append(divider)
    formatted.append("   End of Pulse Report | Generated by Groww Review Pulse Agent")
    formatted.append(divider)

    result = "\n".join(formatted)
    return re.sub(r"\n{3,}", "\n\n", result).strip()
